    const reorderTarget = document.querySelector('.doc-card[data-node-id="' + docC.id + '"]');
    const reorderTransfer = new DataTransfer();
    reorderSource.dispatchEvent(new DragEvent('dragstart', { bubbles: true, dataTransfer: reorderTransfer }));
    reorderTarget.dispatchEvent(new DragEvent('dragover', { bubbles: true, cancelable: true, dataTransfer: reorderTransfer }));
    reorderTarget.dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, dataTransfer: reorderTransfer }));
    checks.dragReordersDocs = docB.order < docC.order;
    const folderRow = document.querySelector('.folder-row[data-node-id="' + folderA.id + '"]');
    const trashNav = document.querySelector('[data-filter="trash"]');
    const trashTransfer = new DataTransfer();
    folderRow.dispatchEvent(new DragEvent('dragstart', { bubbles: true, dataTransfer: trashTransfer }));
    trashNav.dispatchEvent(new DragEvent('dragover', { bubbles: true, cancelable: true, dataTransfer: trashTransfer }));
    trashNav.dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, dataTransfer: trashTransfer }));
    checks.folderTrashCascades = !!folderA.deletedAt && !!folderB.deletedAt && !!docA.deletedAt;
    filter = 'trash'; render();
    checks.trashShowsFolder = !!document.querySelector('#trashFolderTree [data-node-id="' + folderA.id + '"]');
    checks.trashRootExcludesNestedDocs = !document.querySelector('.doc-card[data-node-id="' + docA.id + '"]');
    document.querySelector('#trashFolderTree [data-node-id="' + folderA.id + '"] .folder-chevron').click();
    checks.trashSubfolderCollapses = !document.querySelector('#trashFolderTree [data-node-id="' + folderB.id + '"]');
    document.querySelector('#trashFolderTree [data-node-id="' + folderA.id + '"] .folder-chevron').click();
